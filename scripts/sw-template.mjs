export function renderServiceWorker({ version, shell }) {
  return `/* Generated by scripts/postbuild.mjs. Do not edit this file directly. */
const VERSION=${JSON.stringify(version)};
const SHELL=${JSON.stringify(shell)};

self.addEventListener('install',event=>{
  self.skipWaiting();
  event.waitUntil(caches.open(VERSION).then(cache=>cache.addAll(SHELL)));
});

self.addEventListener('activate',event=>{
  event.waitUntil((async()=>{
    const previous=(await caches.keys()).filter(key=>key.startsWith('psp-')&&key!==VERSION);
    await Promise.all(previous.map(key=>caches.delete(key)));
    await self.clients.claim();
    if(previous.length){
      const clients=await self.clients.matchAll({type:'window'});
      clients.forEach(client=>client.postMessage({type:'APP_UPDATED',version:VERSION}));
    }
  })());
});

self.addEventListener('fetch',event=>{
  if(event.request.method!=='GET')return;
  const url=new URL(event.request.url);
  if(url.origin!==self.location.origin)return;
  if(event.request.mode==='navigate'){
    event.respondWith(fetch(event.request).then(response=>{
      const copy=response.clone();
      caches.open(VERSION).then(cache=>cache.put(event.request,copy));
      return response;
    }).catch(async()=>await caches.match(event.request,{ignoreVary:true})||await caches.match('/index.html',{ignoreVary:true})||await caches.match('/offline.html',{ignoreVary:true})));
    return;
  }
  event.respondWith(caches.match(event.request,{ignoreVary:true}).then(cached=>cached||fetch(event.request).then(response=>{
    if(response.ok)caches.open(VERSION).then(cache=>cache.put(event.request,response.clone()));
    return response;
  })));
});
`;
}
